package main

import (
	"go/ast"
	"go/token"
	"go/types"
	"path"
	"path/filepath"
	"strings"

	"golang.org/x/tools/go/analysis"
)

// cgoHeader heads the files cmd/cgo writes. go vet hands an analyzer a cgo package's user files rewritten by cmd/cgo
// (x.go as x.cgo1.go, its import "C" gone) plus cgo's own _cgo_gotypes.go and _cgo_import.go.
const cgoHeader = "// Code generated by cmd/cgo; DO NOT EDIT."

// source is one of the package's Go files, as the analyzers see it.
type source struct {
	*ast.File
	name string // its real name (//line ignored), but a cgo file's x.cgo1.go is x.go
	rel  string // name, relative to the module root
	test bool   // a _test.go file: tests hold state and read what they like
	gen  bool   // generated (ast.IsGenerated), but not a user file cmd/cgo rewrote
	cgo  bool   // a user file cmd/cgo rewrote: it imported "C"
}

// sources are pass's files, without cmd/cgo's own (_cgo_gotypes.go, _cgo_import.go: cgo's linknames and pointers,
// reported once as the user file's cgo instead).
func sources(pass *analysis.Pass) []source {
	var out []source
	for _, f := range pass.Files {
		switch filepath.Base(pass.Fset.File(f.Pos()).Name()) {
		case "_cgo_gotypes.go", "_cgo_import.go":
			continue
		}
		cgo := len(f.Comments) > 0 && f.Comments[0].List[0].Text == cgoHeader
		// The real name: a hand-written //line x_test.go:1 must not rename a file into a test or an allowed one. Only
		// cmd/cgo's rewrite is named through its //line directives, so x.cgo1.go is x.go.
		name := pass.Fset.PositionFor(f.Package, cgo).Filename
		out = append(out, source{File: f, name: name, rel: relFile(pass, name), test: strings.HasSuffix(name, "_test.go"),
			gen: ast.IsGenerated(f) && !cgo, cgo: cgo})
	}
	return out
}

// relDir is the package's directory relative to its module root ("." at the root), or its import path outside a module.
func relDir(pass *analysis.Pass) string {
	p := pass.Pkg.Path()
	if pass.Module == nil || pass.Module.Path == "" {
		return p
	}
	if p == pass.Module.Path {
		return "."
	}
	if r, ok := strings.CutPrefix(p, pass.Module.Path+"/"); ok {
		return r
	}
	return p
}

// relFile is the module-relative name of one of the package's files.
func relFile(pass *analysis.Pass, name string) string {
	return path.Join(relDir(pass), filepath.Base(name))
}

// list is a comma-separated flag's set.
func list(s string) map[string]bool {
	m := map[string]bool{}
	for _, v := range strings.Split(s, ",") {
		if v = strings.TrimSpace(v); v != "" {
			m[path.Clean(v)] = true
		}
	}
	return m
}

// control reports, for each file of want in this package's directory, that it is missing, or that it did none of what
// it is allowed to (n[file] == 0): the positive control, so a check that stopped seeing fails.
func control(pass *analysis.Pass, want map[string]bool, present map[string]token.Pos, n map[string]int, flag, none string) {
	if len(pass.Files) == 0 {
		return
	}
	for f := range want {
		if path.Dir(f) != relDir(pass) {
			continue
		}
		switch pos, ok := present[f]; {
		case !ok:
			pass.Reportf(pass.Files[0].Package, "%s %s is not in this package", flag, f)
		case n[f] == 0:
			pass.Reportf(pos, "%s %s %s: the check no longer sees it", flag, f, none)
		}
	}
}

// funcOf is the package-level function a call calls (an alias or a dot import is the same object), or nil.
func funcOf(info *types.Info, e ast.Expr) *types.Func {
	c, ok := ast.Unparen(e).(*ast.CallExpr)
	if !ok {
		return nil
	}
	var id *ast.Ident
	switch f := ast.Unparen(c.Fun).(type) {
	case *ast.Ident:
		id = f
	case *ast.SelectorExpr:
		id = f.Sel
	case *ast.IndexExpr: // f[T](...)
		if s, ok := f.X.(*ast.SelectorExpr); ok {
			id = s.Sel
		} else {
			id, _ = f.X.(*ast.Ident)
		}
	}
	fn, _ := info.Uses[id].(*types.Func)
	if fn == nil || fn.Pkg() == nil || fn.Signature().Recv() != nil {
		return nil
	}
	return fn.Origin()
}

// fullName is "path.Name".
func fullName(o types.Object) string { return o.Pkg().Path() + "." + o.Name() }
